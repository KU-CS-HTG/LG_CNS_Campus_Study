from langchain_core.prompts import ChatPromptTemplate
from langchain_openai import ChatOpenAI
from langchain_core.output_parsers import StrOutputParser
from dotenv import load_dotenv

load_dotenv()
llm    = ChatOpenAI(model="gpt-4o-mini", temperature=0)
parser = StrOutputParser()   # AIMessage → str 변환기

prompt = ChatPromptTemplate.from_messages([
    ("system", "당신은 요약 전문가입니다."),
    ("human", "다음 텍스트를{length}줄로 요약해:\n\n{text}")
])

# 파이프로 연결 — 이게 전부입니다!
chain = prompt | llm | parser

# 단건 호출
result = chain.invoke({"length": "3", "text": "유튜브 채널 ‘슈카월드’가 운영하는 팝업스토어 ‘ETF 베이커리’가 개점 일주일 만에 영업 중단을 결정했다. 슈카월드는 지난 5일 소셜미디어(SNS) 공지를 통해 “ETF 베이커리 팝업스토어는 오는 9월7일 영업을 끝으로 잠시 문을 닫고 재정비의 시간을 갖고자 한다”고 밝혔다. 이어 “운영 과정에서 부족했던 점으로 불편과 아쉬움을 드린 데 깊이 사과드린다”고 했다. 그러면서 “지난달 30일 팝업 오픈 이후 많은 관심과 응원을 보내주신 모든 분께 감사드린다”며 “보내주신 질책과 조언을 깊이 새겨 성숙한 모습으로 다시 찾아뵐 수 있도록 노력하겠다”고 덧붙였다. 슈카월드는 지난달 30일 서울 성동구 성수동에서 공간 설계 업체 글로우서울과 협업해 ‘ETF 베이커리’를 열었다. 소금빵·바게트·베이글은 각각 990원, 식빵 1990원, 단팥빵 2930원, 2호 사이즈 복숭아 케이크는 18900원에 책정하는 등 총 35종의 빵과 케이크를 시중보다 저렴하게 판매해 큰 화제를 모았다. 당시 슈카월드 운영자 슈카는 “빵플레이션(빵+인플레이션) 현상에 대응하기 위한 기획”이라며 “가성비를 강조한 새로운 형태의 베이커리 브랜드를 공개한다”고 밝혔다. 또 빵값 구조와 원재료 비용을 직접 분석한 콘텐츠도 공개했다. 슈카월드는 “산지 직송으로 원가를 낮췄고 인건비 절감을 위해 빵 모양을 규격화·단순화했다”며 “아울러 빵값을 ‘마진율’이 아닌 ‘마진액’으로 계산해 원가가 상승하더라도 소비자가에는 반영이 덜 되게끔 조정했다”고 밝혔다. 이를 두고 자영업자 사이에서는 ‘일반 빵집들이 폭리를 취한다는 이미지를 심었다’는 비판이 나왔다. 논란이 일자 슈카는 지난달 31일 유튜브 방송을 통해 “싼 빵을 만들면 좋아할 줄 알았는데 그게 아니었다”며 “죄송하다”고 사과했다. 그는 “자영업자를 비난한 적은 한 번도 없다”며 “나도 자영업자다. 빵값의 구조적인 문제에 대해 이야기하려던 것인데 다른 방향으로 해석돼 안타깝다”고 했다. 그러면서 “기분 상하신 분들이 있다면 오해가 있었던 것 같다”고 덧붙였다."})
print(type(result))   # <class 'str'>
print(result)         # 예상 출력: "1. 핵심 내용 ...\n2. ...\n3. ..."